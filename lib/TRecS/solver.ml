(* Backend that decides a HORS model checking problem with the external TRecS
   model checker (Kobayashi, POPL 2009), run as a separate process.  TRecS
   reads a scheme with a trivial tree automaton; a problem specified by an
   alternating tree automaton is first translated by
   [HOMC.AlternatingToTrivial.convert], which preserves the answer on the
   fragment it accepts and raises on any other problem (an [Error] here).
   The scheme is printed into a per-process scratch directory and TRecS is run
   there; the verdict is read positionally from its output (verified, or
   refuted with a counterexample trace).

   TRecS's input class is a recursion scheme with a deterministic trivial
   automaton (its documentation says so, and its counterexample search
   follows only the first transition for a state and a terminal, so on a
   nondeterministic automaton neither a refutation nor a verification of it
   is guaranteed).  A problem whose trivial automaton has two transitions
   for one state and terminal -- given directly, generated by an EHMTT's
   reduction, or produced by the translation -- is therefore refused with an
   [Error] naming that pair, and is never run; HorSat2 reads such problems.

   An EHMTT is not a HORS problem and is an [Error]: EffCaml reduces it to
   HORS problems and hands them here one by one.  A parse error or output in
   an unexpected shape becomes an [Error], never a verdict.  The scratch
   directory is removed after every run. *)
open Core
open Common
open Automata
open HOMC

type answer =
  | Verified
  | Refuted of string  (** the counterexample trace TRecS printed *)
  | Unreadable of string  (** why the output is no verdict *)

(* Read TRecS 1.2.x's verdict from the lines of its standard output and
   whether it exited successfully.  The output is positional: the third line
   is "Parse error" when the input was refused; the sixth is "The property is
   not satisfied." with the trace on the eighth, or, when the property holds,
   the start of the type environment, which ends in " : ".  Guarantees: a
   verdict needs a successful exit and a complete output (a refutation
   without its trace is no refutation); everything else -- a parse error,
   empty or short output, a failed exit, any other text -- is [Unreadable],
   never a verdict and never an exception. *)
let answer_of_output ~exited_ok lines =
  let line i = List.nth lines i in
  match (line 2, line 5, line 7) with
  | Some "Parse error", _, _ -> Unreadable "TRecS reports a parse error"
  | _ when not exited_ok -> Unreadable "TRecS exited with a failure"
  | _, Some "The property is not satisfied.", Some cex -> Refuted cex
  | _, Some s1, Some _ when String.is_suffix s1 ~suffix:" : " -> Verified
  | _ -> Unreadable "TRecS's output is not in the expected shape"

module type SolverType = sig
  (* Decide a HORS problem; output TRecS prints in any other shape than a
     verdict is an [Error] (see [answer_of_output]). *)
  val solve : ?print_sol:bool -> Problem.t -> Problem.solution Or_error.t

  (* Decide one HORS problem (not an EHMTT), of either automaton dialect,
     answering the verdict together with TRecS's counterexample when it
     refutes the problem; a problem outside TRecS's input class is an
     [Error]. *)
  val solve_rsfd :
    Problem.t -> (Problem.solution * string option) Or_error.t
end

module Make (Config : Config.ConfigType) : SolverType = struct
  let config = Config.config

  module Debug =
    Debug.Make ((val Debug.Config.(if config.verbose then enable else disable)))

  (* Run [f] and then delete the directory [dir] with the files directly in
     it, whether [f] returns or raises; the exception, an alarm's timeout
     included, is re-raised unchanged.  A file or directory already gone, or
     one that cannot be removed, is left as it is: the clean-up never turns
     an answer into a failure. *)
  let remove_dir_after dir f =
    let remove () =
      (try
         Array.iter (Sys_unix.readdir dir) ~f:(fun file ->
             try Core_unix.unlink (Filename.concat dir file)
             with Core_unix.Unix_error _ -> ())
       with Sys_error _ | Core_unix.Unix_error _ -> ());
      try Core_unix.rmdir dir with Core_unix.Unix_error _ -> ()
    in
    match f () with
    | v ->
        remove ();
        v
    | exception exn ->
        remove ();
        raise exn

  (* Run TRecS on one HORS problem in the dialect it reads, answering its
     verdict as reported, with its counterexample trace when it refutes the
     problem. *)
  let run_trecs homc =
    match homc with
    | Problem.RSFD (trs_in, rules, trs_out) ->
        let dir =
          (* TRecS creates its own scratch files in the current directory under
             fixed names ("log<n>.hrs", numbered by an internal counter that
             carries no process id) and unlinks them when it is done, so two
             concurrent runs in one directory delete each other's files and
             TRecS aborts with ENOENT on the unlink.  Its stdout is then short,
             the positional parsing below reads the wrong lines, and the run is
             reported as "HORS verification failed" -- intermittently, only
             under concurrency.  Give every run a directory of its own; that
             also keeps two runs from overwriting the same input file. *)
          sprintf "temp_trecs_p%d" (Pid.to_int @@ Core_unix.getpid ())
        in
        Debug.print
        @@ lazy
             (sprintf "Size of HORS: %d (%d rules)" (RSFD.sizeof rules)
                (List.length rules));
        Debug.print
        @@ lazy
             (sprintf "Number of states of input automaton: %d"
             @@ TreeAutomaton.number_of_states_trs trs_in);
        Debug.print
        @@ lazy
             (sprintf "Number of states of output automaton: %d"
             @@ TreeAutomaton.number_of_states trs_out);
        let res =
          (* the directory is this call's alone (its name carries the process
             id) and nothing reads it once TRecS has answered, so it is
             removed on every exit, an exception or a timeout included;
             otherwise every run leaves one in the directory it ran from *)
          Core_unix.mkdir_p dir;
          remove_dir_after dir (fun () ->
              let filename = Filename.concat dir "input.hors" in
              (* output generated RSFD *)
              Out_channel.with_file filename ~f:(fun channel ->
                  HOMC.Problem.pr (Format.formatter_of_out_channel channel) homc);
              (* TRecS 1.2.1 and 1.2.2 *)
              let cmd =
                (* run TRecS inside that directory, so its fixed-name scratch
                   files land there too; the executable itself is at the
                   repository root, which is where the tool must be started
                   from *)
                sprintf "cd %s && %s input.hors" (Filename.quote dir)
                  (Filename.quote (Filename.concat (Core_unix.getcwd ()) "trecs"))
              in
              let lines, status =
                (* the whole output is read, not just the lines the verdict
                   is in: closing the pipe while TRecS still writes kills it
                   with SIGPIPE, and the exit status would then report our
                   early close as TRecS's failure, losing an answer already
                   printed *)
                Common.Util.Command.read_process cmd ~f:(fun cin ->
                    In_channel.input_lines cin)
              in
              answer_of_output ~exited_ok:(Result.is_ok status) lines)
        in
        (match res with
        | Unreadable reason ->
            Debug.print @@ lazy reason;
            Or_error.error_string ("HORS verification failed: " ^ reason)
        | Verified ->
            Debug.print @@ lazy "verified";
            Ok (Problem.Sat, None)
        | Refuted cex ->
            Debug.print @@ lazy "refuted with a counterexample:";
            Debug.print @@ lazy cex;
            Ok (Problem.Unsat, Some cex))
    | Problem.EHMTT _ -> Or_error.error_string "not a HORS problem"

  (* Decide one HORS problem, answering the verdict together with TRecS's
     counterexample trace when it refutes the problem.  An alternating
     problem is translated first; a trivial automaton with two transitions
     for one state and terminal, given or translated, is refused. *)
  let solve_rsfd homc =
    let translated =
      match homc with
      | Problem.EHMTT _ -> Or_error.error_string "not a HORS problem"
      | Problem.RSFD _ when Problem.reads_alternating homc -> (
          try Ok (AlternatingToTrivial.convert homc)
          with Failure msg ->
            Or_error.error_string
              ("cannot translate the problem for TRecS: " ^ msg))
      | Problem.RSFD _ -> Ok homc
    in
    Or_error.bind translated ~f:(fun homc' ->
        match homc' with
        | Problem.RSFD (_, _, TreeAutomaton.TTA trs) -> (
            match TTA.nondeterministic_pair trs with
            | Some (q, a) ->
                Or_error.error_string
                @@ sprintf
                     "TRecS reads only a deterministic trivial automaton, and \
                      this problem's %shas two transitions for state %s and \
                      terminal %s. Run it with HorSat2 instead (-c \
                      config/solver/horsat2.json; for EffCaml, -c \
                      config/solver/effcaml.json)."
                     (if Problem.reads_alternating homc then
                        "alternating automaton, translated into a trivial \
                         one, "
                      else "trivial automaton ")
                     q a
            | None -> run_trecs homc')
        | _ -> run_trecs homc')

  let solve ?(print_sol = false) homc =
    (match homc with
    | Problem.RSFD _ -> Or_error.map (solve_rsfd homc) ~f:fst
    | Problem.EHMTT _ ->
        Or_error.error_string
          "TRecS decides a HORS problem; an EHMTT program is verified by \
           EffCaml (-c config/solver/effcaml_trecs.json)")
    |> Or_error.map ~f:(fun sol ->
           if print_sol then print_endline (HOMC.Problem.str_of_solution sol);
           sol)
end
