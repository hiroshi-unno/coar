/* Long-running Z3 calls with the OCaml runtime lock released.

   The OCaml bindings of Z3 (z3native_stubs.c, generated by
   scripts/update_api.py) release the runtime lock only around
   Z3_solver_check, Z3_solver_check_assumptions, Z3_simplify and
   Z3_simplify_ex (the list z3_long_funs).  Every other call keeps it for its
   whole duration, and while it is held no other thread of the process runs
   OCaml code and no OCaml signal handler runs, and no other domain gets
   through a stop-the-world collection (a domain inside a C call that keeps
   its lock cannot take part in one, and the others wait for it).  A SIGTERM
   sent at a run's limit is then handled only when the call returns.  The
   calls below were measured to run for minutes in this tool (a fixed-point
   query, a quantifier-elimination tactic) or for tens of seconds (an
   optimisation check), so each is the generated wrapper of the same Z3
   function with the release added, exactly as the generated stub of
   Z3_solver_check does it: the arguments are read out of their OCaml values
   first, the lock is released around the Z3 call alone, and the error check
   and the result follow with the lock held.

   ALL OF THIS FILE'S KNOWLEDGE OF THE BINDINGS' MEMORY LAYOUT IS HERE, in the
   two typedefs below (z3native_stubs.c.pre: MK_PLUS_OBJ and
   Z3_context_plus_data; unchanged from Z3 4.8 to 5.1):
   - every object value (fixedpoint, optimize, tactic, goal, params,
     apply_result, AST, func_decl) is a custom block holding a struct
     { Z3_context_plus cp; T p; };
   - cp points to a struct whose first field is the Z3_context.
   No other assumption is made: no reference count of the bindings is read
   or written, and the one object returned (an apply_result) is a block the
   bindings themselves allocated (n_mk_null_apply_result, holding NULL and
   counted in its context), which is given the result and one Z3 reference
   to it, as the bindings' Z3_apply_result_plus_mk does.  A layout change is
   caught by the property test that compares every call here with the
   bindings' own call on the same input.

   Contract common to every function: the arguments are live objects of one
   context (the caller's OCaml values keep them alive across the release; Z3
   calls no OCaml code during these calls, no callbacks being registered),
   and no other thread uses that context while the call runs (the condition
   the bindings' own released calls impose).  Each raises the bindings'
   exception Z3.Error with Z3's message when the context's error code is set
   after the call, as the generated stub does, and otherwise returns what the
   generated stub returns. */
#include <stdlib.h>
#include <caml/mlvalues.h>
#include <caml/memory.h>
#include <caml/fail.h>
#include <caml/callback.h>
#include <caml/threads.h>

/* the Z3 C API types and functions used, restated from z3_api.h,
   z3_fixedpoint.h and z3_optimization.h */
typedef struct _Z3_context *Z3_context;
typedef struct _Z3_fixedpoint *Z3_fixedpoint;
typedef struct _Z3_optimize *Z3_optimize;
typedef struct _Z3_tactic *Z3_tactic;
typedef struct _Z3_goal *Z3_goal;
typedef struct _Z3_params *Z3_params;
typedef struct _Z3_apply_result *Z3_apply_result;
typedef struct _Z3_ast *Z3_ast;
typedef struct _Z3_func_decl *Z3_func_decl;
typedef int Z3_lbool;
typedef int Z3_error_code;
extern Z3_lbool Z3_fixedpoint_query(Z3_context c, Z3_fixedpoint d, Z3_ast query);
extern Z3_lbool Z3_fixedpoint_query_relations(Z3_context c, Z3_fixedpoint d,
                                              unsigned num_relations,
                                              Z3_func_decl const relations[]);
extern Z3_lbool Z3_optimize_check(Z3_context c, Z3_optimize o,
                                  unsigned num_assumptions,
                                  Z3_ast const assumptions[]);
extern Z3_apply_result Z3_tactic_apply(Z3_context c, Z3_tactic t, Z3_goal g);
extern Z3_apply_result Z3_tactic_apply_ex(Z3_context c, Z3_tactic t, Z3_goal g,
                                          Z3_params p);
extern void Z3_apply_result_inc_ref(Z3_context c, Z3_apply_result r);
extern Z3_error_code Z3_get_error_code(Z3_context c);
extern const char *Z3_get_error_msg(Z3_context c, Z3_error_code err);

/* THE LAYOUT (see the header) */
typedef struct {
  Z3_context ctx;
  /* the bindings' reference count follows; not read here */
} coar_z3_context_plus_data;
typedef struct {
  coar_z3_context_plus_data *cp;
  void *p;
} coar_z3_plus;

static Z3_context coar_ctx_of(value v)
{
  return ((coar_z3_plus *)Data_custom_val(v))->cp->ctx;
}

static void *coar_raw_of(value v)
{
  return ((coar_z3_plus *)Data_custom_val(v))->p;
}

/* the generated stub's error check, with the lock held */
static void coar_check_error(Z3_context ctx)
{
  Z3_error_code ec = Z3_get_error_code(ctx);
  if (ec != 0) {
    const char *msg = Z3_get_error_msg(ctx, ec);
    caml_raise_with_string(*caml_named_value("Z3EXCEPTION"), msg);
  }
}

/* Z3_fixedpoint_query (fixedpoint, query AST) -> Z3_lbool as an int */
value coar_z3_fixedpoint_query_released(value fp, value query)
{
  CAMLparam2(fp, query);
  Z3_context ctx = coar_ctx_of(fp);
  Z3_fixedpoint d = (Z3_fixedpoint)coar_raw_of(fp);
  Z3_ast q = (Z3_ast)coar_raw_of(query);
  Z3_lbool r;
  caml_release_runtime_system();
  r = Z3_fixedpoint_query(ctx, d, q);
  caml_acquire_runtime_system();
  coar_check_error(ctx);
  CAMLreturn(Val_int(r));
}

/* Z3_fixedpoint_query_relations (fixedpoint, func_decl list) -> Z3_lbool */
value coar_z3_fixedpoint_query_relations_released(value fp, value rels)
{
  CAMLparam2(fp, rels);
  CAMLlocal1(iter);
  Z3_context ctx = coar_ctx_of(fp);
  Z3_fixedpoint d = (Z3_fixedpoint)coar_raw_of(fp);
  unsigned n = 0, i;
  Z3_func_decl *a;
  Z3_lbool r;
  for (iter = rels; iter != Val_emptylist; iter = Field(iter, 1)) n++;
  /* one spare slot, so that an empty list still has a valid array */
  a = (Z3_func_decl *)malloc(sizeof(Z3_func_decl) * (n + 1));
  if (a == NULL) caml_raise_out_of_memory();
  for (i = 0, iter = rels; i < n; i++, iter = Field(iter, 1))
    a[i] = (Z3_func_decl)coar_raw_of(Field(iter, 0));
  caml_release_runtime_system();
  r = Z3_fixedpoint_query_relations(ctx, d, n, a);
  caml_acquire_runtime_system();
  free(a);
  coar_check_error(ctx);
  CAMLreturn(Val_int(r));
}

/* Z3_optimize_check (optimize) with no assumptions, as Z3.Optimize.check
   asks it -> Z3_lbool */
value coar_z3_optimize_check_released(value opt)
{
  CAMLparam1(opt);
  Z3_context ctx = coar_ctx_of(opt);
  Z3_optimize o = (Z3_optimize)coar_raw_of(opt);
  Z3_ast none[1];
  Z3_lbool r;
  caml_release_runtime_system();
  r = Z3_optimize_check(ctx, o, 0, none);
  caml_acquire_runtime_system();
  coar_check_error(ctx);
  CAMLreturn(Val_int(r));
}

/* Z3_tactic_apply (tactic, goal, None), or Z3_tactic_apply_ex with p for
   (Some p); [result] is a fresh apply_result block of the
   tactic's context holding NULL (n_mk_null_apply_result), which receives the
   result and one reference to it and is returned.  On an error [result]
   keeps NULL, which its finaliser accepts. */
value coar_z3_tactic_apply_released(value tactic, value goal, value params,
                                    value result)
{
  CAMLparam4(tactic, goal, params, result);
  Z3_context ctx = coar_ctx_of(tactic);
  Z3_tactic t = (Z3_tactic)coar_raw_of(tactic);
  Z3_goal g = (Z3_goal)coar_raw_of(goal);
  int with_params = Is_block(params);
  Z3_params p = with_params ? (Z3_params)coar_raw_of(Field(params, 0)) : NULL;
  Z3_apply_result r;
  caml_release_runtime_system();
  r = with_params ? Z3_tactic_apply_ex(ctx, t, g, p) : Z3_tactic_apply(ctx, t, g);
  caml_acquire_runtime_system();
  coar_check_error(ctx);
  /* [result] is read through its root only now, after the release, during
     which a collection in another thread may have moved the block */
  if (r != NULL) Z3_apply_result_inc_ref(ctx, r);
  ((coar_z3_plus *)Data_custom_val(result))->p = r;
  CAMLreturn(result);
}
